#!/usr/bin/env python3
"""Hash-pinned lifecycle call relocations; never replace function sections.
Only low-frequency control calls are observed. Native stream type extraction is
observed after CFDictionaryGetInt64, avoiding a second dictionary traversal.
"""
import hashlib, os, struct, subprocess, sys, tempfile
from pathlib import Path
HASHES={
 ('AirPlayReceiverServer.o','_HandleHTTPConnectionClose'):'90f0e701d42df6121aa54db0126e88f643b423ac036382489b1d0413aa696d51',
 ('AirPlayReceiverServer.o','_HandleHTTPConnectionMessage'):'ff8ccedb52dc17c19a436d90c20d412192750609308af0f3ac502e4c00b1cabd',
 ('AirPlayReceiverSession.o','AirPlayReceiverSessionSetup'):'d5caa1037884f5cf969c023af70dbcdfae209b778602a8a8fd418f2c8b2eee92',
 ('AirPlayReceiverSession.o','AirPlayReceiverSessionTearDown'):'b0cd13d813b2b5b292ba34edcfaf016b8071534ef1b88bea6b346f4655c095aa',
}
SITES=[
 (1,'AirPlayReceiverServer.o','_HandleHTTPConnectionClose',0x38,'AirPlayReceiverSessionTearDown'),
 (2,'AirPlayReceiverServer.o','_HandleHTTPConnectionMessage',0x42a,'AirPlayReceiverSessionFlushAudio'),
 (3,'AirPlayReceiverServer.o','_HandleHTTPConnectionMessage',0xa1a,'AirPlayReceiverSessionSetup'),
 (4,'AirPlayReceiverServer.o','_HandleHTTPConnectionMessage',0xc74,'AirPlayReceiverSessionTearDown'),
 (5,'AirPlayReceiverSession.o','AirPlayReceiverSessionSetup',0xb0,'AirPlayReceiverSessionTearDown'),
 (6,'AirPlayReceiverSession.o','AirPlayReceiverSessionSetup',0x3a0,'CFDictionaryGetInt64'),
 (7,'AirPlayReceiverSession.o','AirPlayReceiverSessionTearDown',0xda,'CFDictionaryGetInt64'),
]
WRAPS=[(20,'AirPlayAudio_StartAudio'),(21,'AirPlayAudio_StopAudio'),(22,'AirPlayClient_SendMessageTearDown'),(23,'lib_pcm_exit')]
HOOKS=[dict(id=i,member=m,fn=f,off=o,callee=c,name='carbox_music_life_hook_%d'%i) for i,m,f,o,c in SITES]
def fail(s): raise SystemExit('Music lifecycle patch: '+s)
def patch(path,member):
 b=bytearray(path.read_bytes());h=struct.unpack_from('<16sHHIIIIIHHHHHH',b)
 if h[0][:6]!=b'\x7fELF\x01\x01' or h[1:3]!=(1,40) or h[11]!=40:fail('ELF layout')
 ss=[struct.unpack_from('<10I',b,h[6]+40*i) for i in range(h[12])]
 def data(s):return b[s[4]:s[4]+s[5]]
 def st(x,o):return x[o:].split(b'\0',1)[0].decode('ascii')
 names=data(ss[h[13]]);secs={st(names,s[0]):(i,s) for i,s in enumerate(ss)}
 for (m,f),sha in HASHES.items():
  if m==member and hashlib.sha256(data(secs['.text.'+f][1])).hexdigest()!=sha:fail('unknown code '+f)
 tabs=[(i,s) for i,s in enumerate(ss) if s[1]==2]
 if len(tabs)!=1:fail('symbol table')
 ti,tab=tabs[0];strings=data(ss[tab[6]]);syms={}
 for i in range(tab[5]//16):
  off=tab[4]+i*16;rec=struct.unpack_from('<IIIBBH',b,off);name=st(strings,rec[0])
  if name:syms[name]=(i,off,rec)
 for x in HOOKS:
  if x['member']!=member:continue
  si,sec=secs['.text.'+x['fn']];_,rel=secs['.rel.text.'+x['fn']]
  if rel[1]!=9 or rel[6:8]!=(ti,si):fail('relocation layout')
  old=syms[x['callee']];new=syms[x['name']]
  if new[2][5]!=0xfff1:fail('placeholder')
  offsets=[o for o in range(rel[4],rel[4]+rel[5],8) if struct.unpack_from('<I',b,o)[0]==x['off']]
  if len(offsets)!=1 or struct.unpack_from('<I',b,offsets[0]+4)[0]!=(old[0]<<8)|10:fail('unexpected call '+str(x))
  if b[sec[4]+x['off']:sec[4]+x['off']+4]!=bytes.fromhex('fff7feff'):fail('instruction')
  struct.pack_into('<I',b,offsets[0]+4,(new[0]<<8)|10);struct.pack_into('<H',b,new[1]+14,0)
 path.write_bytes(b)
def assembly():
 s='/* Generated by patch_carplay_music_lifecycle.py. Lifecycle calls have no\n * stack arguments. Outbound wrappers tailcall, preserving arbitrary stack args\n * and original caller LR. Native return r0-r3 (including int64) preserved. */\n.syntax unified\n.thumb\n'
 for x in HOOKS:
  n=x['name'];i=x['id'];s+=f'.section .text.{n},"ax",%progbits\n.align 2\n.global {n}\n.type {n},%function\n.thumb_func\n{n}:\n push {{r0-r12,lr}}\n movs r0,#{i}\n movs r1,#0\n mov r2,sp\n bl carbox_music_life_record\n ldmia sp,{{r0-r3}}\n bl {x["callee"]}\n stmia sp,{{r0-r3}}\n str r12,[sp,#48]\n movs r0,#{i}\n movs r1,#1\n mov r2,sp\n bl carbox_music_life_record\n pop {{r0-r12,pc}}\n.size {n},.-{n}\n'
 for i,f in WRAPS:
  n='__wrap_'+f;s+=f'.section .text.{n},"ax",%progbits\n.align 2\n.global {n}\n.type {n},%function\n.thumb_func\n{n}:\n push {{r0-r12,lr}}\n movs r0,#{i}\n movs r1,#0\n mov r2,sp\n bl carbox_music_life_record\n pop {{r0-r12,lr}}\n b __real_{f}\n.size {n},.-{n}\n'
 return s+'.section .note.GNU-stack,"",%progbits\n'
def main(ar,objcopy,source,out):
 out=Path(out);out.parent.mkdir(parents=True,exist_ok=True)
 with tempfile.TemporaryDirectory(dir=out.parent,prefix='.music-life-') as d:
  d=Path(d);a=d/'archive.a';a.write_bytes(Path(source).read_bytes())
  for member in sorted({x['member'] for x in HOOKS}):
   p=d/member;p.write_bytes(subprocess.check_output([ar,'p',source,member]))
   args=[objcopy]+['--add-symbol='+x['name']+'=0,global' for x in HOOKS if x['member']==member]
   subprocess.run(args+[str(p)],check=True);patch(p,member);subprocess.run([ar,'r',str(a),str(p)],check=True,stdout=subprocess.DEVNULL)
  subprocess.run([ar,'s',str(a)],check=True);os.replace(a,out)
 print('Music lifecycle: seven validated control probes; function bytes unchanged')
if __name__=='__main__':
 if sys.argv[1:]==['--assembly']:print(assembly(),end='')
 elif len(sys.argv)==5:main(*sys.argv[1:])
 else:fail('AR OBJCOPY INPUT OUTPUT | --assembly')
